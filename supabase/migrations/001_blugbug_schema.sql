  id uuid primary key default gen_random_uuid(),
  user_id text not null references public.blugbug_users(id) on delete cascade,
  title text not null,
  description text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint blugbug_series_title_length check (char_length(title) between 1 and 180),
  constraint blugbug_series_description_length check (char_length(description) <= 500)
);

create table if not exists public.blugbug_posts (
  id uuid primary key default gen_random_uuid(),
  legacy_id text unique,
  user_id text not null references public.blugbug_users(id) on delete cascade,
  topic_id bigint references public.blugbug_topics(id) on delete set null,
  series_id uuid references public.blugbug_series(id) on delete set null,
  part_number smallint,
  title text not null,
  content_html text not null default '',
  excerpt text not null default '',
  cover_image_url text,
  status text not null default 'draft'
    check (status in ('draft', 'published', 'archived')),
  reply_permission text not null default 'everyone'
    check (reply_permission in ('everyone', 'followers', 'nobody')),
  published_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint blugbug_posts_title_length check (char_length(title) between 1 and 180),
  constraint blugbug_posts_excerpt_length check (char_length(excerpt) <= 500),
  constraint blugbug_posts_part_number check (part_number is null or part_number > 0),
  constraint blugbug_posts_published_time check (status <> 'published' or published_at is not null)
);

create unique index if not exists blugbug_posts_series_part_uidx
  on public.blugbug_posts (series_id, part_number)
  where series_id is not null and part_number is not null;
create index if not exists blugbug_posts_author_created_idx
  on public.blugbug_posts (user_id, created_at desc);
create index if not exists blugbug_posts_public_feed_idx
  on public.blugbug_posts (published_at desc) where status = 'published';
create index if not exists blugbug_posts_topic_feed_idx
  on public.blugbug_posts (topic_id, published_at desc) where status = 'published';
create index if not exists blugbug_posts_title_search_idx
  on public.blugbug_posts using gin (to_tsvector('english', title || ' ' || excerpt));

