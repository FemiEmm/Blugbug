  for select to anon, authenticated
  using (account_status = 'active' or id = (select blugbug_private.current_profile_id()) or (select blugbug_private.is_admin()));
create policy "blugbug_users_create_self" on public.blugbug_users
  for insert to authenticated
  with check (auth_user_id = (select auth.uid()) and account_type = 'person' and account_status = 'active');
create policy "blugbug_users_admin_create_channel" on public.blugbug_users
  for insert to authenticated
  with check ((select blugbug_private.is_admin()) and auth_user_id is null and account_type = 'channel');
create policy "blugbug_users_update_self_or_admin" on public.blugbug_users
  for update to authenticated
  using (id = (select blugbug_private.current_profile_id()) or (select blugbug_private.is_admin()))
  with check (id = (select blugbug_private.current_profile_id()) or (select blugbug_private.is_admin()));
create policy "blugbug_users_admin_delete" on public.blugbug_users
  for delete to authenticated using ((select blugbug_private.is_admin()));

