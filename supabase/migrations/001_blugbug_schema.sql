create policy "blugbug_comments_owner_insert" on public.blugbug_comments for insert to authenticated
  with check (
    user_id = (select blugbug_private.current_profile_id())
    and exists (
      select 1 from public.blugbug_posts p
      where p.id = post_id
        and (p.status = 'published' or p.user_id = (select blugbug_private.current_profile_id()))
        and (p.reply_permission = 'everyone'
          or (p.reply_permission = 'followers' and exists (
            select 1 from public.blugbug_follows f
            where f.follower_id = (select blugbug_private.current_profile_id()) and f.followed_id = p.user_id
          ))
          or p.user_id = (select blugbug_private.current_profile_id()))
