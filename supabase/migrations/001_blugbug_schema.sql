-- Blugbug / Supabase foundation
-- Safe for a Supabase project shared with other applications:
-- every application-owned table, function, trigger, policy and bucket is prefixed blugbug_.
-- Run this entire file once in Supabase Dashboard -> SQL Editor.

begin;

create schema if not exists blugbug_private;
revoke all on schema blugbug_private from public, anon, authenticated;

-- PUBLIC IDENTITY -------------------------------------------------------------

create table if not exists public.blugbug_users (
  id text primary key default gen_random_uuid()::text,
  auth_user_id uuid unique references auth.users(id) on delete set null,
  username text not null,
  chatter_name text not null,
  full_name text not null,
  about_me text not null default '',
  profile_image_url text,
  header_image_url text,
  account_type text not null default 'person'
    check (account_type in ('person', 'channel')),
  account_status text not null default 'active'
    check (account_status in ('active', 'suspended', 'deleted')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint blugbug_users_username_length check (char_length(username) between 2 and 60),
  constraint blugbug_users_handle_format check (chatter_name ~ '^[A-Za-z0-9._-]{2,40}$'),
  constraint blugbug_users_name_length check (char_length(full_name) between 1 and 100),
  constraint blugbug_users_bio_length check (char_length(about_me) <= 500),
  constraint blugbug_users_channel_auth check (account_type <> 'channel' or auth_user_id is null)
);

create unique index if not exists blugbug_users_username_lower_uidx
  on public.blugbug_users (lower(username));
create unique index if not exists blugbug_users_chatter_name_lower_uidx
  on public.blugbug_users (lower(chatter_name));
create index if not exists blugbug_users_auth_user_idx
  on public.blugbug_users (auth_user_id) where auth_user_id is not null;
create index if not exists blugbug_users_discovery_idx
  on public.blugbug_users (account_status, account_type, created_at desc);

-- Kept separate from public profiles. Only SQL Editor / trusted backend code
-- should ever read or write this table.
create table if not exists public.blugbug_admins (
  auth_user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.blugbug_topics (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  name text not null unique,
  description text not null default '',
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  constraint blugbug_topics_slug_format check (slug ~ '^[a-z0-9-]{2,60}$'),
  constraint blugbug_topics_name_length check (char_length(name) between 2 and 80)
);

