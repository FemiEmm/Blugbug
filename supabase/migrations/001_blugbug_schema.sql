-- SECURITY HELPERS -----------------------------------------------------------

create or replace function blugbug_private.current_profile_id()
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select u.id
  from public.blugbug_users u
  where u.auth_user_id = (select auth.uid())
    and u.account_status = 'active'
  limit 1
$$;

create or replace function blugbug_private.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.blugbug_admins a
    where a.auth_user_id = (select auth.uid())
  )
$$;

revoke all on function blugbug_private.current_profile_id() from public;
revoke all on function blugbug_private.is_admin() from public;
grant usage on schema blugbug_private to anon, authenticated;
grant execute on function blugbug_private.current_profile_id() to anon, authenticated;
grant execute on function blugbug_private.is_admin() to anon, authenticated;

create or replace function blugbug_private.touch_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create or replace function blugbug_private.prepare_post()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  if new.status = 'published' and new.published_at is null then
    new.published_at = now();
  end if;
  return new;
end;
$$;

